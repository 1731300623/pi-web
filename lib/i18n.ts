const dictionaries: Record<Locale, Record<string, string>> = {
  "zh-CN": zhCN,
  en: {},
};

let currentLocale: Locale = "zh-CN";

export function getLocale(): Locale {
  if (typeof window !== "undefined") {
    try {
      const stored = localStorage.getItem(STORAGE_KEY) as Locale | null;
      if (stored === "zh-CN" || stored === "en") return stored;
    } catch {
      // ignore
    }
  }
  return currentLocale;
}

export function setLocale(locale: Locale): void {
  currentLocale = locale;
  if (typeof window !== "undefined") {
    try {
      localStorage.setItem(STORAGE_KEY, locale);
    } catch {
      // ignore
    }
  }
}

/** Translate a UI string. Falls back to the source English key when missing. */
export function t(key: string, vars?: Record<string, string | number>): string {
  const locale = typeof window !== "undefined" ? getLocale() : currentLocale;
  const dict = dictionaries[locale] ?? {};
  let out = dict[key] ?? (locale === "en" ? key : zhCN[key] ?? key);
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      out = out.replaceAll(`{${k}}`, String(v));
    }
  }
  return out;
}

/** Helper for template-like messages built at call sites. */
export function tf(template: string, ..._parts: Array<string | number>): string {
  // Prefer exact key match first; otherwise return interpolated Chinese-aware text via t of known fragments.
  return t(template);
}
